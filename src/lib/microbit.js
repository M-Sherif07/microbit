export function runner() {
  let gen = 0;
  return {
    start() {
      const g = ++gen;
      return {
        sleep: ms => new Promise((res, rej) => setTimeout(() => (g === gen ? res() : rej(CANCEL)), Math.max(0, ms))),
        get live() { return g === gen; }
      };
    },
    stop() { gen++; }
  };
}

/* ---------- sound (off unless a page turns it on) ---------- */
let soundOn = false, actx = null;
export function setSound(on) {
  soundOn = on;
  try { if (soundOn) { actx = actx || new (window.AudioContext || window.webkitAudioContext)(); actx.resume(); } } catch (e) { /* no audio */ }
}
export function tone(freq, ms) {
  if (!soundOn || !actx) return;
  try {
    const o = actx.createOscillator(), g = actx.createGain();
    o.type = "square"; o.frequency.value = freq; g.gain.value = 0.035;
    o.connect(g); g.connect(actx.destination);
    o.start(); o.stop(actx.currentTime + ms / 1000);
  } catch (e) { /* ignore */ }
}
